import assert from 'node:assert/strict';
import { optimize, metrics, transforms } from '../layout-optimizer.mjs';
import { inspect } from '../fit-checker.mjs';
const room = { width: 5, depth: 4, height: 3, center: [3, -2] };
const item = (id, x, z, extra = {}) => ({ id, position: [x, 0, z], size: [1, 1, 1], scale: [1, 1, 1], rotationY: 0, mount: 'floor', ...extra });
const objects = [item('fixed', 3, -2, { locked: true }), item('move', 3, -2)];
const saved = JSON.stringify(objects);
const result = await optimize(objects, room, { budgetMs: 10000 });
assert(result.objects, result.reason);
assert(result.result.score > result.baseline.score);
assert.equal(result.result.collisions.length, 0);
assert.equal(result.result.outside.length, 0);
assert.equal(JSON.stringify(result.objects[0]), JSON.stringify(objects[0]));
assert.equal(JSON.stringify(objects), saved, 'Search and preview input remain unchanged');
const preview = transforms(result.objects);
preview[0].position[0] += 20;
assert.equal(JSON.stringify(objects), saved);
assert.notEqual(preview[0].position[0], result.objects[0].position[0], 'Preview transforms are independent');
const impossible = await optimize([item('huge', 3, -2, { size: [8, 1, 8] })], room, { budgetMs: 10000 });
assert(!impossible.objects);
const locked = await optimize([item('a', 3, -2, { locked: true }), item('b', 3, -2, { locked: true })], room);
assert(!locked.objects);
const unknown = await optimize([item('unknown', 3, -2, { size: [null, 1, null] })], room);
assert(!unknown.objects);
const invalidFixed = await optimize([item('a', 9, -2, { locked: true }), item('b', 3, -2)], room, { budgetMs: 10000 });
assert(!invalidFixed.objects);
const cancelled = await optimize(objects, room, { cancelled: () => true });
assert(!cancelled.objects);
assert.equal(inspect(result.objects, room).collisions.length, 0);
assert.equal(metrics(result.objects, room, objects).score, result.result.score);
const exactRoom = { width: 1, depth: 1, height: 3 };
const unchanged = await optimize([item('only', 0, 0)], exactRoom, { budgetMs: 10000 });
assert(!unchanged.objects, 'An equal-scoring arrangement is not presented as an improvement');
let heartbeat = false;
const timer = setTimeout(() => { heartbeat = true; }, 0);
await optimize(objects, room, { budgetMs: 50 });
clearTimeout(timer);
assert(heartbeat, 'Search yields to browser event processing');
console.log('Optimizer checks passed');
