import assert from 'node:assert/strict';
import { box, overlaps, inside, inspect, movableIds } from '../fit-checker.mjs';
const room = { width: 6, depth: 6, height: 3, center: [2, -1] };
const item = (id, x = 2, z = -1, extra = {}) => ({ id, position: [x, 0, z], size: [1, 1, 1], scale: [1, 1, 1], rotationY: 0, mount: 'floor', ...extra });
assert(overlaps(box(item('a')), box(item('b', 2.5))));
assert(!overlaps(box(item('a')), box(item('b', 3))));
const diagonal = item('a', 0, 0, { size: [3, 1, 0.2], rotationY: Math.PI / 4 });
assert(!overlaps(box(diagonal), box(item('b', 0.4, 0.4, { size: [3, 1, 0.2], rotationY: Math.PI / 4 }))));
assert(overlaps(box(diagonal), box(item('b', 0, 0, { rotationY: -Math.PI / 4 }))));
assert(inside(box(item('a')), room));
assert(!inside(box(item('a', 4.8)), room));
assert(!inside(box(item('a', 4.3, -1, { rotationY: Math.PI / 4, size: [2, 1, 2] })), room));
assert(!inside(box(item('a', 2, -1, { scale: [7, 1, 1] })), room));
assert(!overlaps(box(item('a')), box(item('b', 2, -1, { position: [2, 1, -1] }))));
assert.equal(inspect([item('a'), item('b', 2, -1, { hidden: true })], room).collisions.length, 0);
assert(!movableIds([item('a', 2, -1, { locked: true })]).size);
assert(!movableIds([item('a', 2, -1, { mount: 'wall' })]).size);
assert(!movableIds([item('a'), item('vase', 2, -1, { position: [2, 1, -1] })]).has('a'));
console.log('Geometry checks passed');
